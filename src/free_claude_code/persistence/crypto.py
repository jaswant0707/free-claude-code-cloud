"""Cryptographic utilities for Free Claude Code Cloud.

Provides AES-256-GCM authenticated encryption for provider API keys,
deterministic server-side key derivation, key rotation, and secret masking.

TECHNICAL SPECIFICATION:
- Cipher: AES-256-GCM (Galois/Counter Mode, RFC 5116 §5.1, NIST SP 800-38D).
- Nonce: 96-bit (12-byte) cryptographically secure random value generated per encryption.
- Authentication Tag: 128-bit (16-byte) GHASH tag generated by GCM/GHASH arithmetic.
  (Note: AES-GCM uses GHASH for its authentication tag, NOT Poly1305, which is
   used in ChaCha20-Poly1305).
- Key Size: 256 bits (32 bytes).
- Wire Format: base64url(nonce[12B] + ciphertext + ghash_tag[16B]).
"""

from __future__ import annotations

import base64
import hashlib
import os
import secrets
from typing import Final

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

# Salt for deterministic key derivation
_HKDF_SALT: Final[bytes] = b"fcc-cloud-secret-salt-v1"


def get_encryption_key() -> bytes:
    """Derive a deterministic 256-bit AES-GCM key from server environment secrets.
    
    Ensures identical keys across distributed serverless invocations and cold starts.
    """
    explicit_key = os.getenv("FCC_ENCRYPTION_KEY", "").strip()
    if explicit_key:
        return hashlib.sha256(explicit_key.encode("utf-8")).digest()

    from .supabase_client import _DEFAULT_ANON_KEY

    supabase_key = os.getenv("SUPABASE_ANON_KEY", "").strip() or _DEFAULT_ANON_KEY
    seed = f"fcc-aes256-gcm-key-v1:{supabase_key}"
    return hashlib.sha256(seed.encode("utf-8") + _HKDF_SALT).digest()


def encrypt_secret(plaintext: str, key: bytes | None = None) -> str:
    """Encrypt sensitive plaintext using AES-256-GCM.
    
    Each call generates a unique 96-bit (12-byte) cryptographically secure nonce.
    Appends the 16-byte GHASH authentication tag to the ciphertext.
    
    Returns URL-safe base64 string formatted as: nonce (12B) + ciphertext + tag (16B).
    """
    if not plaintext:
        return ""

    aes_key = key if key is not None else get_encryption_key()
    aesgcm = AESGCM(aes_key)
    nonce = secrets.token_bytes(12)
    ciphertext = aesgcm.encrypt(nonce, plaintext.encode("utf-8"), None)
    payload = nonce + ciphertext
    return base64.urlsafe_b64encode(payload).decode("utf-8").rstrip("=")


def decrypt_secret(token: str, key: bytes | None = None) -> str:
    """Decrypt an AES-256-GCM encrypted token.
    
    Extracts the 12-byte nonce, ciphertext, and 16-byte GHASH authentication tag.
    Verifies message integrity using GHASH.
    
    Raises ValueError if ciphertext is invalid, corrupted, or tampered.
    """
    if not token:
        return ""

    aes_key = key if key is not None else get_encryption_key()
    aesgcm = AESGCM(aes_key)
    try:
        padding = "=" * (-len(token) % 4)
        data = base64.urlsafe_b64decode(token + padding)
        if len(data) < 28:  # 12-byte nonce + 16-byte GHASH tag minimum
            raise ValueError("Encrypted data is too short")
        nonce = data[:12]
        ciphertext = data[12:]
        decrypted = aesgcm.decrypt(nonce, ciphertext, None)
        return decrypted.decode("utf-8")
    except Exception as exc:
        raise ValueError(f"Failed to decrypt secret: {exc}") from exc


def rotate_secret(token: str, old_key: bytes, new_key: bytes) -> str:
    """Decrypt a secret using old_key and re-encrypt with new_key under a fresh nonce.
    
    Enables zero-downtime key rotation for stored provider credentials.
    """
    if not token:
        return ""
    plaintext = decrypt_secret(token, key=old_key)
    return encrypt_secret(plaintext, key=new_key)


def mask_secret(secret: str) -> str:
    """Mask sensitive string for display in UI, showing only brief edge characters.
    
    Guarantees raw secret is never revealed in full.
    """
    if not secret:
        return ""
    if len(secret) <= 8:
        return "••••••••"
    prefix_len = min(6, len(secret) // 3)
    suffix_len = min(4, len(secret) // 4)
    return f"{secret[:prefix_len]}...{secret[-suffix_len:]}"
